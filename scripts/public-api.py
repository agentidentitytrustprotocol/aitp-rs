#!/usr/bin/env python3
"""The `aitp` public API snapshots, with signatures.

  generate [--out-dir DIR]   write public-api.stable.txt and
                             public-api.experimental.txt (default
                             crates/aitp)
  check                      regenerate and fail on drift from the
                             committed snapshots
  breaks BASE HEAD           fail when HEAD's stable snapshot breaks BASE's

The stable snapshot is `aitp` built with STABLE_FEATURES. Generating it
fails if a stable signature names an `aitp::` path the snapshot has no
entry for: a type from a private module, which callers can use but never
name. The experimental snapshot lists, per feature in UNSTABLE_FEATURES,
only what that feature adds to the stable surface. Both need the pinned
nightly and cargo-public-api (Makefile).
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

NIGHTLY = os.environ.get("PUBLIC_API_NIGHTLY", "nightly-2026-05-05")
PACKAGE = "aitp"
# The features STABILITY.md promises. `source-ip` comes with `http-server`.
STABLE_FEATURES = ["default", "http-client", "http-server", "pinned-admission", "metrics"]
# Features that carry no promise (STABILITY.md).
UNSTABLE_FEATURES = [
    "client-spki-pinning",
    "experimental-axum",
    "experimental-spiffe-identity",
    "test-util",
]
STABLE_FILE = "public-api.stable.txt"
EXPERIMENTAL_FILE = "public-api.experimental.txt"
HEADER = (
    "# Generated by scripts/public-api.py ({kind}); regenerate with "
    "`make public-api`.\n"
)

DEFINING = re.compile(
    r"^(?:#\[[^\]]*\] )*pub (?:(?:unsafe|async|const|extern \"[^\"]*\") )*"
    r"(?:fn|struct|enum|trait|mod|const|static|type|union|macro) "
)
AITP_PATH = re.compile(r"\baitp(?:::[A-Za-z_][A-Za-z0-9_]*)+")


def run(cmd: list[str]) -> str:
    # CI sets CARGO_TERM_COLOR=always.
    env = {**os.environ, "CARGO_TERM_COLOR": "never"}
    res = subprocess.run(cmd, capture_output=True, text=True, env=env)
    if res.returncode != 0:
        sys.stderr.write(res.stderr)
        sys.exit(f"failed: {' '.join(cmd)}")
    return res.stdout


def strip_generics(s: str) -> str:
    out, depth = [], 0
    for ch in s:
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        elif depth == 0:
            out.append(ch)
    return "".join(out)


def read_path(s: str) -> str:
    """The leading path of `s`, generic arguments included."""
    depth, i = 0, 0
    while i < len(s):
        ch = s[i]
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        elif depth == 0:
            if ch == ":" and s[i : i + 2] == "::":
                i += 2
                continue
            if ch in " (:;=!,":
                break
        i += 1
    return s[:i]


def skip_generics(s: str) -> str:
    """`s` without one leading `<...>` group."""
    if not s.startswith("<"):
        return s
    depth = 0
    for i, ch in enumerate(s):
        depth += {"<": 1, ">": -1}.get(ch, 0)
        if depth == 0:
            return s[i + 1 :]
    return s


def top_level_for(s: str) -> int:
    depth = 0
    for i in range(len(s)):
        depth += {"<": 1, ">": -1, "(": 1, ")": -1}.get(s[i], 0)
        if depth == 0 and s.startswith(" for ", i):
            return i
    return -1


def primary_path(line: str) -> str:
    """The path of the item a snapshot line declares, generics stripped."""
    if line.startswith("impl"):
        rest = skip_generics(line[4:]).lstrip()
        if rest.startswith("!"):
            rest = rest[1:]
        i = top_level_for(rest)
        if i >= 0:
            rest = rest[i + 5 :]
        return strip_generics(read_path(rest))
    m = DEFINING.match(line)
    rest = line[m.end() :] if m else re.sub(r"^(?:#\[[^\]]*\] )*pub (?:use )?", "", line)
    return strip_generics(read_path(rest))


def is_defining(line: str) -> bool:
    return bool(DEFINING.match(line))


def snapshot(features: list[str]) -> list[str]:
    cmd = ["cargo", f"+{NIGHTLY}", "public-api", "--color=never", "-p", PACKAGE, "-sss",
           "--no-default-features", "--features", ",".join(features)]
    return sorted({l for l in run(cmd).splitlines() if l.strip()})


def unnamed_paths(lines: list[str]) -> dict[str, str]:
    """`aitp::` paths the lines name but have no entry for, each with the
    first line that names it."""
    known = {primary_path(l) for l in lines}
    out: dict[str, str] = {}
    for l in lines:
        for path in AITP_PATH.findall(l):
            if path not in known:
                out.setdefault(path, l)
    return out


def generate(out_dir: Path) -> None:
    stable = snapshot(STABLE_FEATURES)
    unnamed = unnamed_paths(stable)
    if unnamed:
        for path, line in sorted(unnamed.items()):
            print(f"::error::a stable signature names {path}, which is not public: {line}",
                  file=sys.stderr)
        sys.exit("make each type a stable signature names public, or change the signature")
    stable_set = set(stable)
    (out_dir / STABLE_FILE).write_text(
        HEADER.format(kind=f"features: {', '.join(STABLE_FEATURES)}")
        + "".join(l + "\n" for l in stable))
    parts = [HEADER.format(kind="what each feature adds to the stable surface; no promise")]
    for feature in UNSTABLE_FEATURES:
        added = [l for l in snapshot([*STABLE_FEATURES, feature]) if l not in stable_set]
        parts.append(f"\n## {feature}\n" + "".join(l + "\n" for l in added))
    (out_dir / EXPERIMENTAL_FILE).write_text("".join(parts))


def body(text: str) -> list[str]:
    """The snapshot lines of `text`, without its `#` comments. A line
    starting `#[` is an item with an attribute, not a comment."""
    return [l for l in text.splitlines() if l and not (l.startswith("#") and not l.startswith("#["))]


def find_breaks(base: list[str], head: list[str]) -> list[str]:
    """Lines of BASE that HEAD breaks: a removed or changed item, or a
    field or variant added to a type without `#[non_exhaustive]`."""
    head_set, base_set = set(head), set(base)
    problems = [f"removed or changed: {l}" for l in base if l not in head_set]

    def types(lines: list[str]) -> dict[str, tuple[str, bool]]:
        out = {}
        for l in lines:
            m = re.match(r"^((?:#\[[^\]]*\] )*)pub (struct|enum) ", l)
            if m:
                out[primary_path(l)] = (m.group(2), "non_exhaustive" in m.group(1))
        return out

    head_types, base_types = types(head), types(base)
    base_paths = {primary_path(l) for l in base}
    for l in head:
        if l in base_set or DEFINING.match(l) or l.startswith(("impl", "pub use ")):
            continue
        if primary_path(l) in base_paths:
            continue  # a changed member, already reported as removed
        # `pub Type::member`: a struct field or an enum variant, or
        # `pub Enum::Variant::field`: a field of an enum variant.
        path = primary_path(l).split("::")
        for parent in ("::".join(path[:-1]), "::".join(path[:-2])):
            kind = head_types.get(parent)
            if kind and parent in base_types:
                if not kind[1] and (kind[0] == "enum" or parent == "::".join(path[:-1])):
                    problems.append(f"added to exhaustive {kind[0]} {parent}: {l}")
                break
    return problems


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("generate")
    g.add_argument("--out-dir", type=Path, default=Path("crates/aitp"))
    sub.add_parser("check")
    b = sub.add_parser("breaks")
    b.add_argument("base", type=Path)
    b.add_argument("head", type=Path)
    args = ap.parse_args()

    if args.cmd == "generate":
        generate(args.out_dir)
        return 0
    if args.cmd == "check":
        with tempfile.TemporaryDirectory() as tmp:
            generate(Path(tmp))
            drift = False
            for name in (STABLE_FILE, EXPERIMENTAL_FILE):
                res = subprocess.run(["diff", "-u", f"crates/aitp/{name}", f"{tmp}/{name}"])
                drift |= res.returncode != 0
        if drift:
            print("the aitp public API changed: review the diff, then run 'make public-api'")
            return 1
        return 0
    problems = find_breaks(body(args.base.read_text()), body(args.head.read_text()))
    for p in problems:
        print(f"::error::{p}")
    print(f"{len(problems)} breaking change(s) to the stable aitp surface")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
