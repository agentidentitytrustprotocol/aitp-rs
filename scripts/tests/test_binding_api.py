"""Self-test for scripts/binding-api.py (stdlib unittest).

Run from the repo root:  python3 -m unittest discover -s scripts/tests
"""

import importlib.util
import os
import tempfile
import unittest
from pathlib import Path

_SCRIPTS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_spec = importlib.util.spec_from_file_location(
    "binding_api", os.path.join(_SCRIPTS, "binding-api.py"))
mod = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(mod)

PYI = '''
from typing import Optional, Union
RevokedJtis = Union[set[str], frozenset[str]]
REVOCATION_LIST_PATH: str
"""Doc."""

class TctIdentity:
    """Doc."""
    peer_aid: str

class AitpAgent:
    @staticmethod
    def generate(suite: str = "ed25519") -> "AitpAgent": ...
    @property
    def aid(self) -> str: ...
    def verify_tct(self, token: str, revoked_jtis: Optional[RevokedJtis] = None) -> TctIdentity:
        """Doc."""
        ...

class ManifestVerificationError(RuntimeError):
    code: str

def compute_aid_jkt(aid: str) -> str:
    """Doc."""
    ...
'''

DTS = '''/* auto-generated by NAPI-RS */
/** Agent. */
export declare class AitpAgent {
  /** Make one. */
  static generate(opts?: GenerateOpts | undefined | null): AitpAgent
  get aid(): string
  constructor(seed: Buffer)
  verifyTct(tctToken: string): JsTctIdentity
}
export type JsTctStore = TctStore
// A comment.
export declare function computeAidJkt(aid: string): string
export declare const REVOCATION_LIST_PATH: string
export interface GenerateOpts {
  suite?: string
}
'''


class Python(unittest.TestCase):
    def test_items(self):
        self.assertEqual(mod.python_items(PYI), sorted([
            "type aitp.RevokedJtis = Union[set[str], frozenset[str]]",
            "const aitp.REVOCATION_LIST_PATH: str",
            "class aitp.TctIdentity",
            "attr aitp.TctIdentity.peer_aid: str",
            "class aitp.AitpAgent",
            "@staticmethod def aitp.AitpAgent.generate(suite: str='ed25519') -> 'AitpAgent'",
            "@property def aitp.AitpAgent.aid(self) -> str",
            "def aitp.AitpAgent.verify_tct(self, token: str, revoked_jtis: Optional[RevokedJtis]=None)"
            " -> TctIdentity",
            "class aitp.ManifestVerificationError(RuntimeError)",
            "attr aitp.ManifestVerificationError.code: str",
            "def aitp.compute_aid_jkt(aid: str) -> str",
        ]))

    def test_a_signature_change_changes_the_snapshot(self):
        changed = PYI.replace("def compute_aid_jkt(aid: str)", "def compute_aid_jkt(aid: bytes)")
        self.assertNotEqual(mod.python_items(PYI), mod.python_items(changed))

    def test_a_docstring_change_does_not(self):
        self.assertEqual(mod.python_items(PYI), mod.python_items(PYI.replace('"""Doc."""', '"""Other."""')))

    def test_names(self):
        module, members, attrs = mod.python_names(mod.python_items(PYI))
        self.assertEqual(module, {"REVOCATION_LIST_PATH", "TctIdentity", "AitpAgent",
                                  "ManifestVerificationError", "compute_aid_jkt"})
        self.assertEqual(members["AitpAgent"], {"generate", "aid", "verify_tct"})
        self.assertEqual(members["TctIdentity"], set())
        self.assertEqual(attrs["ManifestVerificationError"], {"code"})


class Node(unittest.TestCase):
    def test_items(self):
        self.assertEqual(mod.node_items(DTS), sorted([
            "class AitpAgent",
            "AitpAgent.static generate(opts?: GenerateOpts | undefined | null): AitpAgent",
            "AitpAgent.get aid(): string",
            "AitpAgent.constructor(seed: Buffer)",
            "AitpAgent.verifyTct(tctToken: string): JsTctIdentity",
            "type JsTctStore = TctStore",
            "function computeAidJkt(aid: string): string",
            "const REVOCATION_LIST_PATH: string",
            "interface GenerateOpts",
            "GenerateOpts.suite?: string",
        ]))

    def test_a_comment_change_does_not_change_the_snapshot(self):
        self.assertEqual(mod.node_items(DTS), mod.node_items(DTS.replace("Make one.", "Make two.")))

    def test_an_unknown_declaration_fails(self):
        with self.assertRaises(SystemExit):
            mod.node_items("export default 3\n")

    def test_names(self):
        exports, classes = mod.node_names(mod.node_items(DTS))
        self.assertEqual(exports, {"AitpAgent", "computeAidJkt", "REVOCATION_LIST_PATH"})
        self.assertEqual(classes["AitpAgent"], ({"aid", "verifyTct"}, {"generate"}))


class Compare(unittest.TestCase):
    def test_both_directions(self):
        self.assertEqual(mod.compare("m", {"a", "b"}, {"b", "c"}),
                         ["m: c is exported but not in the snapshot",
                          "m: a is in the snapshot but not exported"])

    def test_optional_names_may_be_absent_or_present(self):
        self.assertEqual(mod.compare("m", {"a"}, {"a", "code"}, {"code"}), [])
        self.assertEqual(mod.compare("m", {"a"}, {"a"}, {"code"}), [])


class Committed(unittest.TestCase):
    def test_the_committed_snapshots_are_current(self):
        for path, text in mod.snapshots():
            self.assertEqual(path.read_text(), text, path)

    def test_breaks(self):
        with tempfile.TemporaryDirectory() as d:
            base, new = Path(d) / "a", Path(d) / "b"
            base.write_text("# h\nx\ny\n")
            new.write_text("# h\nx\nz\n")
            self.assertEqual(mod.main(["breaks", str(base), str(new)]), 1)
            self.assertEqual(mod.main(["breaks", str(base), str(base)]), 0)


if __name__ == "__main__":
    unittest.main()
