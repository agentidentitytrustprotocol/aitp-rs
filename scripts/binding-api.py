#!/usr/bin/env python3
"""API snapshots of the language bindings (the bindings' semver gate).

  binding-api.py generate
      write bindings/aitp-py/api.txt (from aitp.pyi) and
      bindings/aitp-node/api.txt (from index.d.ts).
  binding-api.py check
      fail if either snapshot differs from its declarations.
  binding-api.py runtime --python [PYTHON]
  binding-api.py runtime --node [ADDON ...]
      fail unless the built module exports exactly the names its snapshot
      declares: the module's names, and each class's members. PYTHON
      defaults to this interpreter; ADDON defaults to every
      bindings/aitp-node/aitp.*.node, loaded directly (not index.js).
  binding-api.py breaks BASE NEW
      print each BASE line missing from NEW: an item removed or changed.

A snapshot has one line per declared item, sorted, without doc comments.
`aitp.pyi` must match the compiled module (tests/test_stub_signatures.py)
and `index.d.ts` is generated by the build (diffed in bindings.yml), so a
binding signature change reaches the declarations, and from there fails
`check` until the snapshot is regenerated. The experimental declarations
(`aitp_experimental.pyi`, `experimental.d.ts`) have no snapshot.
"""

from __future__ import annotations

import ast
import difflib
import glob
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PY_DIR = ROOT / "bindings" / "aitp-py"
NODE_DIR = ROOT / "bindings" / "aitp-node"
PY_STUB = PY_DIR / "aitp.pyi"
NODE_DTS = NODE_DIR / "index.d.ts"
PY_SNAPSHOT = PY_DIR / "api.txt"
NODE_SNAPSHOT = NODE_DIR / "api.txt"

HEADER = "# Generated by scripts/binding-api.py from {src}. Do not edit.\n"

# ── Python ──────────────────────────────────────────────────────────────


def _decorators(node) -> str:
    names = []
    for d in node.decorator_list:
        target = d.func if isinstance(d, ast.Call) else d
        names.append("@" + ast.unparse(target))
    return " ".join(names) + " " if names else ""


def _signature(fn: ast.FunctionDef) -> str:
    ret = f" -> {ast.unparse(fn.returns)}" if fn.returns else ""
    return f"({ast.unparse(fn.args)}){ret}"


def python_items(source: str) -> list[str]:
    out = []
    for node in ast.parse(source).body:
        if isinstance(node, ast.FunctionDef):
            out.append(f"{_decorators(node)}def aitp.{node.name}{_signature(node)}")
        elif isinstance(node, ast.ClassDef):
            bases = ", ".join(ast.unparse(b) for b in node.bases)
            out.append(f"class aitp.{node.name}" + (f"({bases})" if bases else ""))
            for item in node.body:
                path = f"aitp.{node.name}"
                if isinstance(item, ast.FunctionDef):
                    out.append(f"{_decorators(item)}def {path}.{item.name}{_signature(item)}")
                elif isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name):
                    out.append(f"attr {path}.{item.target.id}: {ast.unparse(item.annotation)}")
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            out.append(f"const aitp.{node.target.id}: {ast.unparse(node.annotation)}")
        elif isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name):
                    out.append(f"type aitp.{t.id} = {ast.unparse(node.value)}")
    return sorted(out)


def python_names(items: list[str]) -> tuple[set[str], dict[str, set[str]], dict[str, set[str]]]:
    """(module names, {class: member names}, {class: `attr` names}) the
    snapshot declares as runtime objects. `type` aliases exist only in the
    stub; an `attr` may be set per instance, so the class need not have it."""
    module, members, attrs = set(), {}, {}
    for line in items:
        m = re.match(r"(?:@\S+ )*(def|class|attr|const) aitp\.([A-Za-z_]\w*)(?:\.([A-Za-z_]\w*))?", line)
        if not m:
            continue
        kind, owner, member = m.groups()
        if member is None:
            module.add(owner)
            if kind == "class":
                members.setdefault(owner, set())
        elif kind == "attr":
            attrs.setdefault(owner, set()).add(member)
        elif not member.startswith("_"):
            members.setdefault(owner, set()).add(member)
    return module, members, attrs


PY_PROBE = """
import inspect, json, aitp
names = [n for n in dir(aitp) if not n.startswith('_') and not inspect.ismodule(getattr(aitp, n))]
classes = {}
for n in names:
    obj = getattr(aitp, n)
    if inspect.isclass(obj):
        classes[n] = [m for m in vars(obj) if not m.startswith('_')]
print(json.dumps({'names': names, 'classes': classes}))
"""

# ── Node ────────────────────────────────────────────────────────────────

JS_COMMENT = re.compile(r"/\*.*?\*/|//[^\n]*", re.S)
CONTAINER = re.compile(r"export (?:declare )?(?:const )?(class|interface|enum) (\w+)[^{]*\{\s*$")


def node_items(source: str) -> list[str]:
    out, owner = [], None
    for raw in JS_COMMENT.sub("", source).splitlines():
        line = " ".join(raw.split())
        if not line:
            continue
        if owner is not None:
            if line == "}":
                owner = None
            else:
                out.append(f"{owner}.{line.rstrip(',;')}")
            continue
        m = CONTAINER.match(line)
        if m:
            kind, owner = m.groups()
            out.append(f"{kind} {owner}")
            continue
        m = re.match(r"export (?:declare )?(function|const|type) (.*)$", line)
        if m:
            out.append(f"{m.group(1)} {m.group(2).rstrip(';')}")
        else:
            raise SystemExit(f"index.d.ts: unrecognised declaration: {raw.strip()}")
    return sorted(out)


def node_names(items: list[str]) -> tuple[set[str], dict[str, tuple[set[str], set[str]]]]:
    """(addon export names, {class: (prototype names, static names)})."""
    exports, classes, kinds = set(), {}, {}
    for line in items:
        m = re.match(r"(class|interface|enum|function|const|type) (\w+)", line)
        if m:
            kinds[m.group(2)] = m.group(1)
            if m.group(1) in ("class", "enum", "function", "const"):
                exports.add(m.group(2))
            if m.group(1) == "class":
                classes[m.group(2)] = (set(), set())
    for line in items:
        owner, _, member = line.partition(".")
        if kinds.get(owner) != "class" or not member:
            continue
        static = member.startswith("static ")
        member = re.sub(r"^(static |get |set )+", "", member)
        name = re.match(r"\w+", member).group(0)
        if name != "constructor":
            classes[owner][1 if static else 0].add(name)
    return exports, classes


NODE_PROBE = """
const m = require(process.argv[1]);
const classes = {};
for (const [k, v] of Object.entries(m)) {
  if (typeof v === 'function' && v.prototype && Object.getOwnPropertyNames(v.prototype).length > 1) {
    classes[k] = [
      Object.getOwnPropertyNames(v.prototype).filter((n) => n !== 'constructor'),
      Object.getOwnPropertyNames(v).filter((n) => !['length', 'name', 'prototype', 'arguments', 'caller'].includes(n)),
    ];
  }
}
console.log(JSON.stringify({ names: Object.keys(m), classes }));
"""

# ── commands ────────────────────────────────────────────────────────────


def render(items: list[str], src: str) -> str:
    return HEADER.format(src=src) + "".join(f"{i}\n" for i in items)


def snapshots() -> list[tuple[Path, str]]:
    return [
        (PY_SNAPSHOT, render(python_items(PY_STUB.read_text()), "bindings/aitp-py/aitp.pyi")),
        (NODE_SNAPSHOT, render(node_items(NODE_DTS.read_text()), "bindings/aitp-node/index.d.ts")),
    ]


def read_items(path: Path) -> list[str]:
    return [l for l in path.read_text().splitlines() if l and not l.startswith("# ")]


def compare(label: str, declared: set[str], actual: set[str], optional=frozenset()) -> list[str]:
    out = [f"{label}: {n} is exported but not in the snapshot"
           for n in sorted(actual - declared - optional)]
    out += [f"{label}: {n} is in the snapshot but not exported" for n in sorted(declared - actual)]
    return out


def probe(cmd: list[str]) -> dict:
    return json.loads(subprocess.run(cmd, check=True, capture_output=True, text=True).stdout)


def runtime_problems(args: list[str]) -> list[str]:
    if not args or args[0] not in ("--python", "--node"):
        raise SystemExit("runtime needs --python [PYTHON] or --node [ADDON ...]")
    if args[0] == "--python":
        python = args[1] if len(args) > 1 else sys.executable
        got = probe([python, "-c", PY_PROBE])
        module, members, attrs = python_names(read_items(PY_SNAPSHOT))
        out = compare("aitp", module, set(got["names"]))
        for cls, names in sorted(got["classes"].items()):
            if cls in members:
                out += compare(f"aitp.{cls}", members[cls], set(names), attrs.get(cls, set()))
        return out
    addons = args[1:] or sorted(glob.glob(str(NODE_DIR / "aitp.*.node")))
    if not addons:
        raise SystemExit(f"no aitp.*.node in {NODE_DIR}")
    exports, classes = node_names(read_items(NODE_SNAPSHOT))
    out = []
    for addon in addons:
        label = Path(addon).name
        got = probe(["node", "-e", NODE_PROBE, str(Path(addon).resolve())])
        out += compare(label, exports, set(got["names"]))
        for cls, (proto, static) in sorted(got["classes"].items()):
            if cls in classes:
                out += compare(f"{label} {cls}.prototype", classes[cls][0], set(proto))
                out += compare(f"{label} {cls} (static)", classes[cls][1], set(static))
    return out


def main(argv: list[str]) -> int:
    cmd = argv[0] if argv else ""
    if cmd == "generate":
        for path, text in snapshots():
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
        return 0
    if cmd == "check":
        bad = 0
        for path, text in snapshots():
            current = path.read_text() if path.exists() else ""
            if current != text:
                bad += 1
                rel = str(path.relative_to(ROOT))
                print(f"::error::{rel} is out of date; run `make binding-api` and review the diff")
                sys.stdout.writelines(difflib.unified_diff(
                    current.splitlines(True), text.splitlines(True), rel, "declarations"))
        print(f"{2 - bad}/2 binding API snapshot(s) up to date")
        return 1 if bad else 0
    if cmd == "runtime":
        found = runtime_problems(argv[1:])
        for p in found:
            print(f"::error::{p}")
        print(f"{len(found)} difference(s) between the built binding and its API snapshot")
        return 1 if found else 0
    if cmd == "breaks" and len(argv) == 3:
        new = set(read_items(Path(argv[2])))
        gone = [l for l in read_items(Path(argv[1])) if l not in new]
        for l in gone:
            print(f"::error::removed or changed: {l}")
        print(f"{len(gone)} breaking change(s) to the binding API")
        return 1 if gone else 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
